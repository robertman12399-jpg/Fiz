  /* ---------- ОБРАБОТКА ---------- */
  function inputVal(id) { const el = document.getElementById(id || "ft-inp"); return parseNum(el ? el.value : ""); }

  function onClick(e) {
    const n = e.target.closest("[data-ft]");
    if (!n) return;
    const a = n.getAttribute("data-ft");

    if (a === "close") { host.style.display = "none"; return; }
    if (a === "next") { S.stage++; S.fb = {}; draw(); return; }
    if (a === "restart") { S.stage = 0; S.fb = {}; S.controlScore = null; draw(); return; }
    if (a === "control-retry") { S.fb = {}; S.controlScore = null; draw(); return; }

    if (a === "concept") {
      const t = T().concept, i = +n.getAttribute("data-i");
      if (i === t.correct) { S.fb.c = { solved: true }; try { window.FizMatApp; } catch (_) {} award(15); }
      else S.fb.c = { wrong: i };
      draw(); return;
    }
    if (a === "units") {
      const u = T().units;
      if (near(inputVal(), u.answer, u.tol)) { S.fb.u = { solved: true }; award(20); }
      else S.fb.u = { wrong: true };
      draw(); return;
    }
    if (a === "graph") {
      const g = T().graph;
      if (near(inputVal(), g.answer, g.tol)) { S.fb.g = { solved: true }; award(20); }
      else S.fb.g = { wrong: true };
      draw(); return;
    }
    if (a === "model") {
      const i = +n.getAttribute("data-i"), o = +n.getAttribute("data-o");
      const it = T().model.items[i];
      if (o === it.correct) { S.fb["m" + i] = { solved: true }; award(10); }
      else S.fb["m" + i] = { wrong: o };
      draw(); return;
    }
    if (a === "levels") {
      const i = +n.getAttribute("data-i"), t = T().levels.tasks[i];
      if (near(inputVal("ft-inp-l" + i), t.answer, t.tol)) { S.fb["l" + i] = { solved: true }; award(15); }
      else S.fb["l" + i] = { wrong: true };
      draw(); return;
    }
    if (a === "mistakes") {
      const i = +n.getAttribute("data-i"), o = +n.getAttribute("data-o");
      const c = T().mistakes.cases[i];
      if (o === c.correct) { S.fb["mk" + i] = { solved: true }; award(15); }
      else S.fb["mk" + i] = { wrong: o };
      draw(); return;
    }
    if (a === "transfer") {
      const t = T().transfer;
      if (near(inputVal(), t.answer, t.tol)) { S.fb.tr = { solved: true }; award(30); }
      else S.fb.tr = { wrong: true };
      draw(); return;
    }
    if (a === "repeat") {
      const i = +n.getAttribute("data-i"), o = +n.getAttribute("data-o");
      const c = T().repeat.quick[i];
      if (o === c.correct) { S.fb["r" + i] = { solved: true }; award(5); }
      else S.fb["r" + i] = { wrong: o };
      draw(); return;
    }
    if (a === "control-mc") {
      const i = +n.getAttribute("data-i"), o = +n.getAttribute("data-o");
      const it = T().control.items[i];
      S.fb["c" + i] = { answered: true, pick: o, ok: o === it.correct };
      draw(); return;
    }
    if (a === "control-num") {
      const i = +n.getAttribute("data-i"), it = T().control.items[i];
      const ok = near(inputVal("ft-inp-c" + i), it.answer, it.tol);
      S.fb["c" + i] = { answered: true, ok: ok };
      draw(); return;
    }
    if (a === "control-finish") {
      const C = T().control;
      let score = 0;
      C.items.forEach((_, i) => { if (S.fb["c" + i] && S.fb["c" + i].ok) score++; });
      S.controlScore = score;
      if (score / C.items.length >= 0.6) award(50);
      draw(); return;
    }
  }

